create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  role text not null default 'user' check (role in ('admin','user')),
  created_at timestamptz not null default now()
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  site text not null,
  province text,
  pea text not null,
  kwh numeric,
  baht numeric,
  co2 numeric,
  project_year integer not null,
  star boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.projects enable row level security;
alter table public.profiles enable row level security;

-- ผู้ใช้งานทั่วไปอ่านข้อมูลได้
drop policy if exists "Public can read projects" on public.projects;
create policy "Public can read projects" on public.projects
for select to anon, authenticated using (true);

-- ผู้ดูแลเท่านั้นที่เพิ่ม/แก้ไข/ลบได้
drop policy if exists "Admins can insert projects" on public.projects;
create policy "Admins can insert projects" on public.projects
for insert to authenticated
with check (exists (select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

drop policy if exists "Admins can update projects" on public.projects;
create policy "Admins can update projects" on public.projects
for update to authenticated
using (exists (select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'))
with check (exists (select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

drop policy if exists "Admins can delete projects" on public.projects;
create policy "Admins can delete projects" on public.projects
for delete to authenticated
using (exists (select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

-- ให้ผู้ใช้ที่ล็อกอินอ่าน profile ของตัวเองได้
drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile" on public.profiles
for select to authenticated using (id=auth.uid());

-- อัปเดตเวลาแก้ไขข้อมูล
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists projects_updated_at on public.projects;
create trigger projects_updated_at before update on public.projects
for each row execute function public.set_updated_at();

